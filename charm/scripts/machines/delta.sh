# NCSA Delta, CPU nodes. TESTED: 1 node 2026-09-10 (1-120 cores, both
# layouts, REPORT in results/); multi-node: see MULTINODE.md for status.
#
# Sourced by scripts/common.sh. Every variable can be overridden from the
# environment, so a one-off run needs no edit here.

# Node: 2x AMD EPYC 7763, 128 cores, 8 NUMA domains of 16. One process per
# domain, 15 PEs each, the 16th core of each domain left to the OS: 120 PEs
# per node.
: "${NUMA_DOMAINS:=8}"
: "${CORES_PER_DOMAIN:=16}"
: "${PES_PER_DOMAIN:=15}"

# Slingshot 11 / CXI. Required at >= ~6 processes per node, or the CXI
# provider runs out of hardware List Entries and aborts in flow control
# (README "Fabric environment").
export FI_CXI_RX_MATCH_MODE=${FI_CXI_RX_MATCH_MODE:-hybrid}
# Only needed with LCI older than 06748025 (P^2*D KVS keys against Cray PMI2's
# per-job quota); harmless otherwise. Reconverse main pins ca88ce2c, which IS
# older -- build.sh overrides the pin, this is the insurance if it doesn't.
export PMI_MAX_KVS_ENTRIES=${PMI_MAX_KVS_ENTRIES:-1000}

# +lci_ndevices by processes per node: small, never near the PE count. Each
# device registers a 512 MB packet pool and the NIC runs out of memory
# registration past ~60 devices per node. Measured optimum: 4 up to 6
# processes per node, 2 at 8.
ndev_for() {  # procs_per_node
  if   [ "$1" -ge 8 ]; then echo 2
  elif [ "$1" -gt 1 ]; then echo 4
  else echo 0
  fi
}

# Where things live. Datasets are regenerated by gendata.sh, never committed.
: "${BH_WORK:=/work/hdd/mzu/rao1/bh-multinode}"
: "${DATA:=/work/hdd/mzu/rao1/bh-scaling/data}"
: "${LOGS:=$BH_WORK/logs}"
: "${DATAGEN:=/u/rao1/DataGenerator}"

# Launch: srun inside the allocation. --cpu-bind=none so +pemap does the
# pinning; --unbuffered or libfabric's fatal line is lost and a crash looks
# like a hang; --kill-on-bad-exit so one aborting rank ends the step.
LAUNCH_FLAGS="--cpu-bind=none --unbuffered --kill-on-bad-exit=1"

# ---- Scheduling (used by submit.sh) ---------------------------------------
# Measured 2026-10-14 (sshare, sbatch --test-only); fairshare moves daily.
#   cpu-interactive: <= 4 nodes, <= 1 h, ONE job submitted per user; starts
#                    within ~1 h on either account. Use it whenever it fits.
#   cpu:             anything bigger. Start time depends on the account's
#                    fairshare (10/14: mzu 2-4 nodes ~6.5 h, 8 nodes ~10.5 h;
#                    rfp ~3 days). submit.sh asks --test-only on every
#                    account and takes the earliest.
ACCOUNTS=${ACCOUNTS:-"mzu-delta-cpu rfp-delta-cpu"}
FAST_PARTITION=cpu-interactive
FAST_MAX_NODES=4
FAST_MAX_MINUTES=60
BIG_PARTITION=cpu
# --exclusive --mem=0, never --cpus-per-task: a partial cpuset may not contain
# the +pemap cores and every PE then aborts in CmiSetCPUAffinity.
SBATCH_NODE_FLAGS="--exclusive --mem=0"
