# Sourced by scripts/common.sh. Every variable can be overridden from the
# environment, so a one-off run needs no edit here.

# Node: 2x AMD EPYC 7763, 128 cores, no SMT, NPS4: 8 NUMA domains of 16
# (0-15, 16-31, ..., 112-127) -- the same layout as a Delta CPU node. One
# process per domain, 15 PEs each. Unlike delta.sh, the FIRST core of each
# domain is the one left free (PE_OFFSET_IN_DOMAIN=1 -> cores 1-15, 17-31,
# ...): the layout validated on Anvil 2026-08-11 (charm-notes machines/anvil.md),
# which cured 10 ms scheduling holes from OS work on core 0 of a domain.
# The LOGIN nodes are different hardware (EPYC 7543, 32 cores, 4 domains):
# never read the layout, or time anything, there.
: "${NUMA_DOMAINS:=8}"
: "${CORES_PER_DOMAIN:=16}"
: "${PES_PER_DOMAIN:=15}"
: "${PE_OFFSET_IN_DOMAIN:=1}"

# InfiniBand HDR (mlx5_0), one HCA per node. LCI's default backend is ibv;
# nothing Slingshot-specific applies. PMI_MAX_KVS_ENTRIES is harmless
# insurance (see delta.sh).
unset FI_CXI_RX_MATCH_MODE
export PMI_MAX_KVS_ENTRIES=${PMI_MAX_KVS_ENTRIES:-1000}

# +lci_ndevices by processes per node, as on Delta (README "Fabric
# environment"); not yet re-measured on Anvil.
ndev_for() {  # procs_per_node
  if   [ "$1" -ge 8 ]; then echo 2
  elif [ "$1" -gt 1 ]; then echo 4
  else echo 0
  fi
}

# libreconverse links the hwloc module's libhwloc.so.5 (the only hwloc module
# on Anvil, 1.11.13), which only the module puts on the library path.
if command -v module >/dev/null 2>&1; then module load hwloc 2>/dev/null; fi

# The Charm++ build that build.sh recorded, so a binary that carries no rpath
# to the reconverse/LCI shared libraries still finds them.
if [ -f "$(dirname "${BASH_SOURCE[0]}")/../../.build.env" ]; then
  # shellcheck disable=SC1091
  . "$(dirname "${BASH_SOURCE[0]}")/../../.build.env"
  export LD_LIBRARY_PATH=$CHARM_PATH/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}
fi

# Where things live. $HOME has a 25 GB quota; everything goes to the project
# space. Note Anvil predefines WORK=/anvil/projects/x-asc050025 -- hence the
# BH_ prefix. Datasets are regenerated by gendata.sh or, for the issue-7
# three-galaxy input, by hand (data/PROVENANCE.md); never committed.
: "${BH_WORK:=/anvil/projects/x-asc050025/x-lkale/software/barnesHut}"
: "${DATA:=$BH_WORK/data}"
: "${LOGS:=$BH_WORK/logs}"
: "${DATAGEN:=$BH_WORK/DataGenerator}"

# Launch: srun inside the allocation. --mpi=pmi2 because LCI bootstraps
# through PMI and Anvil's Slurm provides it only when asked (plain srun
# prints nothing and hangs). --cpu-bind=none so +pemap does the pinning;
# --unbuffered or an abort before the banner is lost; --kill-on-bad-exit so
# one aborting rank ends the step. Single-process runs go through srun too:
# a bare ./barnes inside an sbatch allocation waits for ranks that never join.
LAUNCH_FLAGS="--mpi=pmi2 --cpu-bind=none --unbuffered --kill-on-bad-exit=1"
# An sbatch --cpus-per-task leaks into every inner srun as its per-step
# default and makes multi-process steps ask for more CPUs than the job has;
# Slurm's default per-task binding would give each process one CPU.
unset SLURM_CPUS_PER_TASK
export SLURM_CPU_BIND=none SRUN_CPU_BIND=none

# ---- Scheduling (used by submit.sh) ---------------------------------------
# One allocation. Partition caps are hard limits (charm-notes anvil.md):
#   shared:   1 node max, 4 d; --exclusive for a whole node, billed like
#             wholenode. Also highmem (1 node, same hardware, often idle) and
#             debug (2 nodes, 2 h) -- force with PARTITION= when shared is
#             backed up.
#   wholenode/standard: up to 16 nodes, whole nodes, queues but backfills
#             short jobs within minutes to hours.
# Measured 2026-10-27 17:00 CDT (sbatch --test-only, 1 node, 30 min):
# standard 1.3 h, wide 1.6 h, debug 8 h, highmem 14 h, shared 13 d,
# wholenode 5 d. So the 'fast' route is standard, and the estimates move;
# submit.sh asks every time.
ACCOUNTS=${ACCOUNTS:-asc050025}
FAST_PARTITION=standard
FAST_MAX_NODES=16
FAST_MAX_MINUTES=240
BIG_PARTITION=wholenode
# --exclusive: on shared, the whole node (all 128 cores and its memory in the
# job cgroup, so +pemap can bind to any of them); redundant but harmless on
# wholenode. Anvil rejects --mem=0 ("disabled on Anvil").
SBATCH_NODE_FLAGS="--exclusive"
